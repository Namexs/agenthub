// Export contract ABIs from the Foundry build output into the web app.
//
// Usage (from the repo root, after `forge build` in packages/contracts):
//   node packages/contracts/script/export-abis.mjs
//
// The ABIs are COMMITTED as TypeScript modules in apps/web/lib/abis/ —
// the web app never imports from packages/contracts/out/ (out/ is
// gitignored build output, and the Next.js build must not depend on a
// forge build having run). Regenerate after any contract change and
// commit the diff alongside it.
//
// TypeScript modules (not JSON): wagmi/viem need the ABI as a literal
// type for function-name inference, and `as const` cannot be applied to
// an imported JSON value (TS1355). The generated file is a plain array
// literal with `as const`, so inference works.
//
// Only the ABIs the frontend needs are exported: AgentGate, QuestManager,
// Reputation, Achievement. The Agent ID contract is an external ERC-721;
// the frontend uses a minimal balanceOf ABI (see lib/contracts.ts).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contractsOut = join(here, '..', 'out');
const abisDir = join(here, '..', '..', '..', 'apps', 'web', 'lib', 'abis');

const CONTRACTS = ['AgentGate', 'QuestManager', 'Reputation', 'Achievement'];

function constName(contract) {
  return contract.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase() + '_ABI';
}

mkdirSync(abisDir, { recursive: true });

for (const name of CONTRACTS) {
  const artifact = JSON.parse(
    readFileSync(join(contractsOut, `${name}.sol`, `${name}.json`), 'utf8'),
  );
  if (!artifact.abi || artifact.abi.length === 0) {
    throw new Error(`no ABI in artifact for ${name}`);
  }
  const target = join(abisDir, `${name}.ts`);
  const content =
    `// Generated by packages/contracts/script/export-abis.mjs — do not edit by hand.\n` +
    `// Regenerate after any contract change (see the script header).\n` +
    `export const ${constName(name)} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(target, content);
  console.log(`wrote ${target} (${artifact.abi.length} entries)`);
}
