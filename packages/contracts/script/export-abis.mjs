// Export contract ABIs from the Foundry build output into the web app.
//
// Usage (from the repo root, after `forge build` in packages/contracts):
//   node packages/contracts/script/export-abis.mjs           # regenerate (writes files)
//   node packages/contracts/script/export-abis.mjs --check   # CI guard: exit 1 on drift, writes nothing
//
// The ABIs are COMMITTED as TypeScript modules in apps/web/lib/abis/ —
// the web app never imports from packages/contracts/out/ (out/ is
// gitignored build output, and the Next.js build must not depend on a
// forge build having run). Regenerate after any contract change and
// commit the diff alongside it.
//
// TypeScript modules (not JSON): wagmi/viem need the ABI as a literal
// type for function-name inference, and `as const` cannot be applied to
// an imported JSON value (TS1355). The generated file is a plain array
// literal with `as const`, so inference works.
//
// Only the ABIs the frontend needs are exported: AgentGate, QuestManager,
// Reputation, Achievement. The Agent ID contract is an external ERC-721;
// the frontend uses a minimal balanceOf ABI (see lib/contracts.ts).
//
// PHASE 8 (PH7-I09): --check mode regenerates in memory and diffs
// against the committed files, so CI can fail on ABI drift without
// overwriting anything. The script also asserts the artifacts were
// built with the solc version pinned in foundry.toml (and that all four
// artifacts agree on one compiler version) — regenerating from a
// wrong-toolchain build must fail loudly instead of producing a diff
// that looks like contract drift.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contractsOut = join(here, '..', 'out');
const contractsRoot = join(here, '..');
const abisDir = join(here, '..', '..', '..', 'apps', 'web', 'lib', 'abis');

const CONTRACTS = ['AgentGate', 'QuestManager', 'Reputation', 'Achievement'];

function fail(message) {
  console.error(`export-abis: ${message}`);
  process.exit(1);
}

const args = process.argv.slice(2);
const checkMode = args.includes('--check');
for (const arg of args) {
  if (arg !== '--check') fail(`unknown argument: ${arg}\nUsage: node export-abis.mjs [--check]`);
}

function constName(contract) {
  return contract.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase() + '_ABI';
}

function generatedContent(name, artifact) {
  return (
    `// Generated by packages/contracts/script/export-abis.mjs — do not edit by hand.\n` +
    `// Regenerate after any contract change (see the script header).\n` +
    `export const ${constName(name)} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
  );
}

// The solc version pinned in foundry.toml (e.g. "0.8.39") — the single
// source of truth; no second copy of the version lives in this script.
function pinnedSolcVersion() {
  const toml = readFileSync(join(contractsRoot, 'foundry.toml'), 'utf8');
  const match = toml.match(/^\s*solc_version\s*=\s*"([^"]+)"/m);
  return match ? match[1] : null;
}

const pinnedSolc = pinnedSolcVersion();
if (!pinnedSolc) {
  console.error(
    'export-abis: warning: no solc_version pin found in foundry.toml — skipping solc check',
  );
}

mkdirSync(abisDir, { recursive: true });

const drifted = [];
const compilerVersions = new Map();

for (const name of CONTRACTS) {
  const artifact = JSON.parse(
    readFileSync(join(contractsOut, `${name}.sol`, `${name}.json`), 'utf8'),
  );
  if (!artifact.abi || artifact.abi.length === 0) {
    throw new Error(`no ABI in artifact for ${name}`);
  }
  // PH7-I09: the artifact must come from the pinned solc. Metadata is
  // a JSON string in some Foundry versions and an object in others.
  const metadata =
    typeof artifact.metadata === 'string' ? JSON.parse(artifact.metadata) : artifact.metadata;
  const compilerVersion = metadata?.compiler?.version;
  if (!compilerVersion) {
    fail(`${name}: artifact metadata has no compiler version — refusing to export from it`);
  }
  if (
    pinnedSolc &&
    compilerVersion !== pinnedSolc &&
    !compilerVersion.startsWith(`${pinnedSolc}+`)
  ) {
    fail(
      `${name}: artifact built with solc ${compilerVersion}, but foundry.toml pins ${pinnedSolc} — rebuild with the pinned toolchain`,
    );
  }
  compilerVersions.set(compilerVersion, [...(compilerVersions.get(compilerVersion) ?? []), name]);

  const target = join(abisDir, `${name}.ts`);
  const content = generatedContent(name, artifact);
  if (checkMode) {
    if (!existsSync(target)) {
      drifted.push(`${target} (missing — run export-abis.mjs to generate it)`);
    } else if (readFileSync(target, 'utf8') !== content) {
      drifted.push(`${target} (differs from regeneration — run export-abis.mjs and commit the diff)`);
    }
  } else {
    writeFileSync(target, content);
    console.log(`wrote ${target} (${artifact.abi.length} entries)`);
  }
}

// All four artifacts must agree on one compiler version — a mixed
// build (e.g. a stale out/ partially rebuilt) must not export silently.
if (compilerVersions.size > 1) {
  const detail = [...compilerVersions.entries()]
    .map(([version, names]) => `${version}: ${names.join(', ')}`)
    .join('; ');
  fail(`artifacts disagree on the solc version (${detail}) — run a clean forge build`);
}

if (checkMode) {
  if (drifted.length > 0) {
    fail(`ABI drift detected in ${drifted.length} file(s):\n${drifted.map((d) => `  - ${d}`).join('\n')}`);
  }
  console.log(`export-abis --check: all ${CONTRACTS.length} committed ABIs match regeneration`);
}
